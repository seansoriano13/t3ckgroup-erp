-- Issue #179 — `serial_no` on sales_opportunities is the SOR Register's
-- first column and its default sort, but it exists in production and not
-- in staging: nothing in supabase/migrations ever created it, so it must
-- have been added directly against production outside a migration. Adding
-- it here, guarded by IF NOT EXISTS, reconciles staging up to what
-- production already has without touching production's copy (identity
-- sequences and existing values are untouched where the column is already
-- there).
alter table public.sales_opportunities
  add column if not exists serial_no bigint generated by default as identity not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'sales_opportunities_serial_no_key'
      and conrelid = 'public.sales_opportunities'::regclass
  ) then
    alter table public.sales_opportunities
      add constraint sales_opportunities_serial_no_key unique (serial_no);
  end if;
end $$;
