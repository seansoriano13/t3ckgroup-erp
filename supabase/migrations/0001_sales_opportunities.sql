create extension if not exists pgcrypto;

create sequence if not exists sales_opportunity_no_seq start 7190;

-- ── Opportunities ───────────────────────────────────────────────────────────
create table if not exists public.sales_opportunities (
  id                   uuid primary key default gen_random_uuid(),

  -- Assigned by trigger on insert. Immutable thereafter.
  opportunity_no       text unique,

  -- registration_date is the dispute tiebreaker under Annex C.4. Immutable.
  registration_date    date        not null default current_date,
  registered_at        timestamptz not null default now(),
  registered_by        uuid        not null references public.employees(id),

  -- Lead source register (Annex D.2). Stored as fixed category + free-text
  -- entity, e.g. 'LGU' + 'Bayambang'.
  lead_source          text not null,
  lead_source_detail   text,

  client_name          text not null,
  contact_person       text,
  project_title        text not null,

  -- The sheet's "Sales Division" column.
  project_type         text          not null default 'SSP',
  expected_value       numeric(18,2) not null default 0,
  expected_award_date  date,

  deal_owner_id        uuid references public.employees(id),
  support_sales_1_id   uuid references public.employees(id),
  support_sales_2_id   uuid references public.employees(id),
  sales_director_id    uuid references public.employees(id),

  status               text not null default 'LEAD',
  lost_reason          text,

  is_deleted           boolean     not null default false,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),

  constraint sales_opportunities_lead_source_chk check (lead_source in (
    'LGU','NGA','GOCC','BFP','PNP','MIL','DRRM','CORPORATE','REFERRAL',
    'WEBSITE','FACEBOOK','TIKTOK','SHOPEE','LAZADA','EXHIBITION','REPEAT_CLIENT'
  )),
  constraint sales_opportunities_project_type_chk check (project_type in (
    'SSP','CP','STRATEGIC'
  )),
  constraint sales_opportunities_status_chk check (status in (
    'LEAD','QUALIFIED','PROPOSAL_SUBMITTED','BID_SUBMITTED','NEGOTIATION',
    'AWARDED','PO_RECEIVED','PROJECT_DELIVERY','COLLECTION','CLOSED_WON',
    'RETENTION','CLOSED_LOST'
  ))
);

create index if not exists sales_opportunities_status_idx
  on public.sales_opportunities (status);
create index if not exists sales_opportunities_deal_owner_idx
  on public.sales_opportunities (deal_owner_id);
create index if not exists sales_opportunities_registered_by_idx
  on public.sales_opportunities (registered_by);
create index if not exists sales_opportunities_lead_source_idx
  on public.sales_opportunities (lead_source);
create index if not exists sales_opportunities_reg_date_idx
  on public.sales_opportunities (registration_date desc);
create index if not exists sales_opportunities_active_idx
  on public.sales_opportunities (is_deleted, status);

-- ── Notes / activity timeline ───────────────────────────────────────────────
create table if not exists public.sales_opportunity_logs (
  id              uuid primary key default gen_random_uuid(),
  opportunity_id  uuid not null references public.sales_opportunities(id) on delete cascade,
  -- NULL author_id means the entry was generated by the system.
  author_id       uuid references public.employees(id),
  type            text not null default 'COMMENT',
  content         text not null,
  metadata        jsonb,
  created_at      timestamptz not null default now(),

  constraint sales_opportunity_logs_type_chk check (type in ('COMMENT','SYSTEM'))
);

create index if not exists sales_opportunity_logs_opp_idx
  on public.sales_opportunity_logs (opportunity_id, created_at);

-- ── Opportunity number assignment ───────────────────────────────────────────
-- nextval() is atomic, so concurrent registrations cannot collide. A failed
-- insert burns a number, which is auditable and preferable to a gap-free
-- sequence that races. Non-null values pass through untouched so the Google
-- Sheet backfill can carry its own numbers; afterwards run:
--   select setval('sales_opportunity_no_seq', <max existing number>);
create or replace function public.sales_opportunities_set_no()
returns trigger language plpgsql as $$
begin
  if new.opportunity_no is null then
    new.opportunity_no :=
      'S' || lpad(nextval('sales_opportunity_no_seq')::text, 5, '0');
  end if;
  return new;
end $$;

drop trigger if exists trg_sales_opportunities_set_no on public.sales_opportunities;
create trigger trg_sales_opportunities_set_no
  before insert on public.sales_opportunities
  for each row execute function public.sales_opportunities_set_no();

-- ── Immutability guard ──────────────────────────────────────────────────────
-- Ownership disputes are resolved on registration date (Annex C.4), so these
-- three columns must never change once the record exists.
create or replace function public.sales_opportunities_guard()
returns trigger language plpgsql as $$
begin
  if new.opportunity_no is distinct from old.opportunity_no then
    raise exception 'opportunity_no is immutable (% -> %)',
      old.opportunity_no, new.opportunity_no;
  end if;
  if new.registration_date is distinct from old.registration_date then
    raise exception 'registration_date is immutable — it determines deal ownership';
  end if;
  if new.registered_by is distinct from old.registered_by then
    raise exception 'registered_by is immutable';
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trg_sales_opportunities_guard on public.sales_opportunities;
create trigger trg_sales_opportunities_guard
  before update on public.sales_opportunities
  for each row execute function public.sales_opportunities_guard();

