-- SOR Code — `SOR-357` — the SOR's own reference, for people and anything
-- outside this database (chat, paper, Odoo notes, exports). It is `serial_no`
-- with a prefix, stored rather than formatted in the UI, so every query,
-- export and integration reads the same string instead of each rebuilding it.
--
-- No zero padding on purpose: `SOR-00357` reads like an Odoo `S0####`
-- quotation number, the exact confusion that retired opportunity_no
-- (_archive/0025_retire_opportunity_no.sql).
--
-- Tables that point at an SOR keep referencing `id`. sor_code is the human
-- reference, not a key to copy into other rows.

-- Generated from serial_no, never written: it cannot drift from the number it
-- names. The explicit ::text cast keeps the expression immutable (text ||
-- bigint resolves to the STABLE textanycat, which a generated column rejects).
alter table public.sales_opportunities
  add column if not exists sor_code text
  generated always as ('SOR-' || serial_no::text) stored;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'sales_opportunities_sor_code_key'
      and conrelid = 'public.sales_opportunities'::regclass
  ) then
    alter table public.sales_opportunities
      add constraint sales_opportunities_sor_code_key unique (sor_code);
  end if;
end $$;

-- serial_no is `generated by default`, so an UPDATE could still rewrite it —
-- and with it the SOR Code people have already quoted. Guarded alongside the
-- two fields that were already immutable.
create or replace function public.sales_opportunities_guard()
returns trigger language plpgsql as $$
begin
  if new.registration_date is distinct from old.registration_date then
    raise exception 'registration_date is immutable — it determines deal ownership';
  end if;
  if new.registered_by is distinct from old.registered_by then
    raise exception 'registered_by is immutable';
  end if;
  if new.serial_no is distinct from old.serial_no then
    raise exception 'serial_no is immutable — it is the SOR Code people reference';
  end if;
  return new;
end $$;
